//go:build ignore

// Run through npm run browser after bundling the TypeScript frontend.
package main

import (
	"crypto/sha256"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
)

func main() {
	if err := generate(); err != nil {
		fmt.Fprintln(os.Stderr, "fingerprint JavaScript bundle:", err)
		os.Exit(1)
	}
}

func generate() error {
	const dir = "handlers/static/js"
	bundle := filepath.Join(dir, "main.js")
	data, err := os.ReadFile(bundle)
	if err != nil {
		return err
	}
	filename := fmt.Sprintf("main.%x.js", sha256.Sum256(data))
	source, err := format.Source(fmt.Appendf(nil, `// Code generated by npm run browser; DO NOT EDIT.

package templates

import "app/routes"

const MainScriptPath = %q

// MainScriptURL builds the fingerprinted bundle URL for this handler.
func MainScriptURL(links routes.Links) (string, error) {
 return links.StaticURL(MainScriptPath)
}
`, "js/"+filename))
	if err != nil {
		return err
	}
	if err := os.Rename(bundle, filepath.Join(dir, filename)); err != nil {
		return err
	}
	if err := os.WriteFile("templates/javascript_generated.go", source, 0644); err != nil {
		return err
	}
	previous, err := filepath.Glob(filepath.Join(dir, "main.*.js"))
	if err != nil {
		return err
	}
	previous = append(previous, filepath.Join(dir, "browser.js"))
	for _, name := range previous {
		if filepath.Base(name) != filename {
			if err := os.Remove(name); err != nil && !os.IsNotExist(err) {
				return err
			}
		}
	}
	return nil
}
