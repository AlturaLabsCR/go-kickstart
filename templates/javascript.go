//go:build ignore

// Run through npm run browser after bundling the TypeScript frontend.
package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/base64"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
)

func main() {
	if err := generate(); err != nil {
		fmt.Fprintln(os.Stderr, "fingerprint JavaScript bundle:", err)
		os.Exit(1)
	}
}

func generate() error {
	const dir = "handlers/static/js"
	bundle := filepath.Join(dir, "main.js")
	data, err := os.ReadFile(bundle)
	if err != nil {
		return err
	}
	if bytes.Contains(bytes.ToLower(data), []byte("</script")) {
		return fmt.Errorf("JavaScript bundle contains an HTML script closing tag")
	}
	digest := sha256.Sum256(data)
	filename := fmt.Sprintf("main.%x.js", digest)
	source, err := format.Source(fmt.Appendf(nil, `// Code generated by npm run browser; DO NOT EDIT.

package templates

import "app/routes"
import "github.com/a-h/templ"

const MainScriptPath = %q
const MainScriptCSPHash = %q

// Only the generated local bundle is rendered as raw HTML.
var mainScript = templ.NewOnceHandle(templ.WithComponent(templ.Raw(%q)))

// MainScript renders the inline module once per document render context.
func MainScript() templ.Component { return mainScript.Once() }

// MainScriptURL builds the fingerprinted bundle URL for this handler.
func MainScriptURL(links routes.Links) (string, error) {
 return links.StaticURL(MainScriptPath)
}
`, "js/"+filename, "sha256-"+base64.StdEncoding.EncodeToString(digest[:]), "<script id=\"main-script\" type=\"module\">"+string(data)+"</script>"))
	if err != nil {
		return err
	}
	if err := os.Rename(bundle, filepath.Join(dir, filename)); err != nil {
		return err
	}
	if err := os.WriteFile("templates/javascript_generated.go", source, 0644); err != nil {
		return err
	}
	previous, err := filepath.Glob(filepath.Join(dir, "main.*.js"))
	if err != nil {
		return err
	}
	previous = append(previous, filepath.Join(dir, "browser.js"))
	for _, name := range previous {
		if filepath.Base(name) != filename {
			if err := os.Remove(name); err != nil && !os.IsNotExist(err) {
				return err
			}
		}
	}
	return nil
}
