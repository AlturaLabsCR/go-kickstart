//go:build ignore

// Run through go generate ./templates to download and fingerprint Semantic CSS.
package main

import (
	"archive/tar"
	"bytes"
	"compress/gzip"
	"crypto/sha256"
	"fmt"
	"go/format"
	"io"
	"net/http"
	"os"
	"path/filepath"
	"regexp"
	"strings"
	"time"
)

// semanticCommit pins https://github.com/tavocg/semantic (2026-11-13).
// Update this commit and run go generate ./templates to update the stylesheet.
const semanticCommit = "523373d36f06256d9ff60c2723a8c9235a368b3b"

func main() {
	if err := generate(); err != nil {
		fmt.Fprintln(os.Stderr, "generate Semantic CSS:", err)
		os.Exit(1)
	}
}

func generate() error {
	client := &http.Client{Timeout: time.Minute}
	resp, err := client.Get("https://codeload.github.com/tavocg/semantic/tar.gz/" + semanticCommit)
	if err != nil {
		return err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return fmt.Errorf("download: %s", resp.Status)
	}
	gz, err := gzip.NewReader(resp.Body)
	if err != nil {
		return err
	}
	defer gz.Close()

	// Read source files without extracting archive paths onto the filesystem.
	files := make(map[string][]byte)
	prefix := "semantic-" + semanticCommit + "/"
	const cssDir = "themes/semantic/assets/css/"
	archive := tar.NewReader(gz)
	for {
		header, err := archive.Next()
		if err == io.EOF {
			break
		}
		if err != nil {
			return err
		}
		name, ok := strings.CutPrefix(header.Name, prefix)
		if !ok || header.Typeflag != tar.TypeReg {
			continue
		}
		if !strings.HasPrefix(name, cssDir) && name != "LICENSE" && name != "licenses/preflight.txt" {
			continue
		}
		files[name], err = io.ReadAll(archive)
		if err != nil {
			return fmt.Errorf("read %s: %w", name, err)
		}
	}
	for _, name := range []string{cssDir + "main.css", "LICENSE", "licenses/preflight.txt"} {
		if len(files[name]) == 0 {
			return fmt.Errorf("missing source file %s", name)
		}
	}

	// Inline main.css imports in upstream order, preserving license comments.
	imports := regexp.MustCompile(`(?m)^@import "([^"]+)";\r?$`)
	var missing string
	css := imports.ReplaceAllFunc(files[cssDir+"main.css"], func(line []byte) []byte {
		name := string(imports.FindSubmatch(line)[1])
		content, ok := files[cssDir+name]
		if !ok {
			missing = name
		}
		return content
	})
	if missing != "" {
		return fmt.Errorf("missing CSS import %s", missing)
	}
	if bytes.Contains(css, []byte("@import")) {
		return fmt.Errorf("stylesheet contains unresolved CSS imports")
	}
	filename := fmt.Sprintf("semantic.%x.css", sha256.Sum256(css))
	source, err := format.Source(fmt.Appendf(nil, `// Code generated by go generate ./templates; DO NOT EDIT.
// Source: https://github.com/tavocg/semantic/tree/%s

package templates

import "strings"

// SemanticStylesheetURL returns the fingerprinted stylesheet URL under rootPrefix.
func SemanticStylesheetURL(rootPrefix string) string {
	return strings.TrimRight(rootPrefix, "/") + %q
}
`, semanticCommit, "/s/css/"+filename))
	if err != nil {
		return err
	}

	staticDir := filepath.Join("..", "handlers", "static", "css")
	if err := os.MkdirAll(staticDir, 0755); err != nil {
		return err
	}
	for _, output := range []struct {
		path string
		data []byte
	}{
		{filepath.Join(staticDir, filename), css},
		{filepath.Join(staticDir, "semantic.LICENSE.txt"), files["LICENSE"]},
		{filepath.Join(staticDir, "semantic-preflight.LICENSE.txt"), files["licenses/preflight.txt"]},
		{"stylesheet_generated.go", source},
	} {
		if err := writeFile(output.path, output.data); err != nil {
			return err
		}
	}

	// Remove only obsolete generated stylesheets after publishing their replacement.
	previous, err := filepath.Glob(filepath.Join(staticDir, "semantic.*.css"))
	if err != nil {
		return err
	}
	for _, name := range previous {
		if filepath.Base(name) != filename {
			if err := os.Remove(name); err != nil {
				return err
			}
		}
	}
	return nil
}

func writeFile(name string, data []byte) error {
	file, err := os.CreateTemp(filepath.Dir(name), ".semantic-*")
	if err != nil {
		return err
	}
	defer os.Remove(file.Name())
	if _, err := file.Write(data); err != nil {
		file.Close()
		return err
	}
	if err := file.Chmod(0644); err != nil {
		file.Close()
		return err
	}
	if err := file.Close(); err != nil {
		return err
	}
	return os.Rename(file.Name(), name)
}
