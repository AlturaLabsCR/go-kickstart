//go:build ignore

// Run through go generate ./templates to download and fingerprint Semantic CSS.
package main

import (
	"crypto/sha256"
	"fmt"
	"go/format"
	"io"
	"net/http"
	"os"
	"path/filepath"
	"time"
)

// semanticTag pins https://github.com/tavocg/semantic/releases.
// Update this tag and run go generate ./templates to update the stylesheet.
const semanticTag = "v1.0.3"

func main() {
	if err := generate(); err != nil {
		fmt.Fprintln(os.Stderr, "generate Semantic CSS:", err)
		os.Exit(1)
	}
}

func generate() error {
	client := &http.Client{Timeout: time.Minute}
	releaseURL := "https://github.com/tavocg/semantic/releases/download/" + semanticTag + "/semantic.css"
	sourceURL := "https://raw.githubusercontent.com/tavocg/semantic/" + semanticTag + "/"
	files := make(map[string][]byte)
	for name, url := range map[string]string{
		"semantic.css":           releaseURL,
		"LICENSE":                sourceURL + "LICENSE",
		"licenses/preflight.txt": sourceURL + "licenses/preflight.txt",
	} {
		data, err := download(client, url)
		if err != nil {
			return fmt.Errorf("download %s: %w", name, err)
		}
		if len(data) == 0 {
			return fmt.Errorf("empty download %s", name)
		}
		files[name] = data
	}

	css := files["semantic.css"]
	filename := fmt.Sprintf("semantic.%x.css", sha256.Sum256(css))
	source, err := format.Source(fmt.Appendf(nil, `// Code generated by go generate ./templates; DO NOT EDIT.
// Source: %s

package templates

import "app/routes"

const SemanticStylesheetPath = %q

// SemanticStylesheetURL builds the fingerprinted stylesheet URL for this handler.
func SemanticStylesheetURL(links routes.Links) (string, error) {
 return links.StaticURL(SemanticStylesheetPath)
}
`, releaseURL, "css/"+filename))
	if err != nil {
		return err
	}

	staticDir := filepath.Join("..", "handlers", "static", "css")
	if err := os.MkdirAll(staticDir, 0755); err != nil {
		return err
	}
	for _, output := range []struct {
		path string
		data []byte
	}{
		{filepath.Join(staticDir, filename), css},
		{filepath.Join(staticDir, "semantic.LICENSE.txt"), files["LICENSE"]},
		{filepath.Join(staticDir, "semantic-preflight.LICENSE.txt"), files["licenses/preflight.txt"]},
		{"stylesheet_generated.go", source},
	} {
		if err := writeFile(output.path, output.data); err != nil {
			return err
		}
	}

	// Remove only obsolete generated stylesheets after publishing their replacement.
	previous, err := filepath.Glob(filepath.Join(staticDir, "semantic.*.css"))
	if err != nil {
		return err
	}
	for _, name := range previous {
		if filepath.Base(name) != filename {
			if err := os.Remove(name); err != nil {
				return err
			}
		}
	}
	return nil
}

func download(client *http.Client, url string) ([]byte, error) {
	resp, err := client.Get(url)
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("%s", resp.Status)
	}
	return io.ReadAll(resp.Body)
}

func writeFile(name string, data []byte) error {
	file, err := os.CreateTemp(filepath.Dir(name), ".semantic-*")
	if err != nil {
		return err
	}
	defer os.Remove(file.Name())
	if _, err := file.Write(data); err != nil {
		file.Close()
		return err
	}
	if err := file.Chmod(0644); err != nil {
		file.Close()
		return err
	}
	if err := file.Close(); err != nil {
		return err
	}
	return os.Rename(file.Name(), name)
}
